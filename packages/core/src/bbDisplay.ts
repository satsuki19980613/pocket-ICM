/**
 * ポーカーチェイスの BB 表示の丸め（さつき決定 2026-09-11）。
 *
 * ゲームは BB 換算の値（スタック・ベット・ポット）を**小数第 2 位で四捨五入して小数第 1 位まで**
 * 表示する。公式の記載は見つからなかったので、同じ局面をチップ表示と BB 表示で撮った組から
 * 実測で確定した（公式 Web 版・BB 200）:
 *   5,850 → 29.25 → 29.3 / 6,250 → 31.25 → 31.3 / 12,050 → 60.25 → 60.3 / 5,950 → 29.75 → 29.8
 * x.25 がすべて x.3 になるので偶数丸め（銀行丸め）ではなく四捨五入。Android 実機でも
 * 2.75 → 2.8（切り捨てではない）・3.0455 → 3.0（切り上げではない）。
 * 末尾の .0 は表示しない（「Pot : 3 BB」「29 BB」）。
 *
 * 用途: アプリが計算した厳密値（例: ポット 0.5 + 1 + 0.25×5 = 2.75）を、ゲームの画面と同じ
 * 形（2.8）で見せる／画面から読んだ値と突き合わせる。
 */

/**
 * BB 換算の値を、ポーカーチェイスの表示と同じく小数第 2 位で四捨五入する。
 *
 * `Math.round(x * 10) / 10` は使わない: 足し算で生じる浮動小数の誤差で、1.2 + 0.15 が
 * 1.3499999999999999 になり 1.3 に丸まる（正しくは 1.4）。まず 100 万分の 1 単位の整数に寄せて
 * ノイズだけを消し、整数演算で丸める（千分の 1 単位で寄せると 2.7496 が 2.750 扱いになり、
 * 二重丸めで 2.8 と誤る）。
 */
export function roundBbDisplay(x: number): number {
  if (!Number.isFinite(x)) return x;
  const micro = Math.round(Math.abs(x) * 1e6);
  const tenths = Math.floor((micro + 50_000) / 100_000); // 小数第 2 位を四捨五入
  const v = tenths / 10;
  return x < 0 ? -v : v;
}

/** 画面と同じ表記（小数第 1 位まで・末尾の .0 は付けない）。例: 2.75 → "2.8", 3 → "3"。 */
export function formatBbDisplay(x: number): string {
  return String(roundBbDisplay(x));
}
