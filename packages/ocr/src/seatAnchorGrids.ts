/**
 * 機種別・席名アンカーの静的グリッド（OCR_PHASE2 §B3 補強・さつき決定 2026-09-09）。
 *
 * 純アンカー方式は「黄色名を検出→その重心を席アンカーに」して読むが、機種/解像度で
 * ゲーム描画の中心軸・席の広がりがずれると、検出重心が装飾（Dディスク・黄色バッジ・
 * コイン・スケール天秤）に引っ張られて名前中心を外し、スタック切り出しが数字を外して
 * NaN になる（実測: 超ワイド劣化Android 1320×540 で CO=BL の stack 欠測→組立失敗）。
 *
 * 対策（静的・機種別）: アスペクト帯ごとに **名前中心のフラクショナル座標グリッド** を
 * 実測較正して持ち、該当機種では検出重心の代わりにこのグリッドで nameBox 中心を確定する。
 * グリッドは AI 目視で各席の黄色名テキスト中心（左右中心×フォント縦中心）に合わせ込んで
 * 検証済み（scripts の較正・4体のサブエージェント測定→目視確認, 2026-09-09）。
 *
 * 適用範囲は**問題が実測された帯のみ**（既存の Android 2730・iPhone 1792 は現行の検出が
 * 正しく読めており、グリッドを当てると回帰リスクだけが増えるため当てない）。未知機種は
 * undefined を返し、現行のランドマーク検出のまま（＝回帰ゼロ）。新しい機種で破綻が実測され
 * 次第、その帯のグリッドを追加する。
 */

import type { Slot } from './seatEnum.js';

/** 席名中心のフラクショナル座標（占有席のみ意味を持つ）。 */
export type SeatAnchorGrid = Partial<Record<Slot, { readonly x: number; readonly y: number }>>;

/**
 * 超ワイド劣化 Android（アスペクト ~2.44・実測 1310×536 / 1320×540）の名前中心グリッド。
 * 2 枚の実機フレームで席別に AI 目視較正（両フレーム重複席 TR/BR/BC は ±0.001 一致）。
 * BL(=CO) は左脇の黄色八角コイン混入を除去して 0.2545（素朴重心 0.230 の左寄りを是正）。
 */
export const GRID_SUPERWIDE_2P44: SeatAnchorGrid = {
  TL: { x: 0.2981, y: 0.2892 },
  TC: { x: 0.5305, y: 0.1980 },
  TR: { x: 0.7677, y: 0.2894 },
  BR: { x: 0.8138, y: 0.6439 },
  BC: { x: 0.6142, y: 0.7817 }, // hero
  BL: { x: 0.2545, y: 0.6450 },
};

/**
 * アスペクト比から静的グリッドを選ぶ。既知の破綻帯のみ返し、それ以外は undefined
 * （＝現行のランドマーク検出のまま・回帰ゼロ）。
 */
export function pickSeatAnchorGrid(aspect: number): SeatAnchorGrid | undefined {
  // 超ワイド帯（~2.44）: 縮小/加工された劣化 Android フレーム。中心軸・席広がりが較正機と
  // 大きく異なり検出重心が装飾に負ける。実測 2 機（1310/1320）はいずれもこの帯。
  if (aspect >= 2.38 && aspect <= 2.52) return GRID_SUPERWIDE_2P44;
  return undefined;
}
